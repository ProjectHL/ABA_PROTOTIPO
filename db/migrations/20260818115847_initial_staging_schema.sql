create function private.prevent_client_organization_reassignment()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.organization_id is distinct from old.organization_id then
    raise exception using
      errcode = '42501',
      message = 'client_organization_is_immutable';
  end if;
  new.updated_at := now();
  return new;
end;
$$;

revoke all on function private.prevent_client_organization_reassignment() from public, anon, authenticated;

create trigger clients_prevent_organization_reassignment
before update on public.clients
for each row execute function private.prevent_client_organization_reassignment();

