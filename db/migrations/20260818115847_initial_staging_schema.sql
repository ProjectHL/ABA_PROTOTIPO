create table public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(btrim(name)) between 1 and 120),
  status text not null default 'active' check (status in ('active', 'archived')),
  test_run_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.memberships (
  organization_id uuid not null references public.organizations(id) on delete restrict,
  user_id uuid not null references auth.users(id) on delete restrict,
  role text not null check (role in ('admin', 'clinician', 'viewer')),
  test_run_id uuid,
  created_at timestamptz not null default now(),
  primary key (organization_id, user_id)
);

create index memberships_user_organization_idx
  on public.memberships (user_id, organization_id);

create table public.clients (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete restrict,
  clinical_id text not null check (char_length(btrim(clinical_id)) between 1 and 64),
  initials text not null check (char_length(btrim(initials)) between 1 and 12),
  primary_language text not null check (char_length(btrim(primary_language)) between 1 and 32),
  birth_date date not null check (birth_date <= current_date),
  living_arrangement text check (living_arrangement is null or char_length(btrim(living_arrangement)) between 1 and 500),
  status text not null default 'active' check (status in ('active', 'archived')),
  test_run_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint clients_organization_clinical_id_key unique (organization_id, clinical_id)
);

create index clients_organization_status_idx
  on public.clients (organization_id, status);

create table public.guardians (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.clients(id) on delete restrict,
  initials text not null check (char_length(btrim(initials)) between 1 and 12),
  position integer not null check (position >= 0),
  test_run_id uuid,
  created_at timestamptz not null default now(),
  unique (client_id, position)
);

create index guardians_client_idx on public.guardians (client_id);

create table public.siblings (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.clients(id) on delete restrict,
  initials text not null check (char_length(btrim(initials)) between 1 and 12),
  birth_date date check (birth_date is null or birth_date <= current_date),
  position integer not null check (position >= 0),
  test_run_id uuid,
  created_at timestamptz not null default now(),
  unique (client_id, position)
);

create index siblings_client_idx on public.siblings (client_id);

