-- Final local security pass: preserve the functional RPC contracts while
-- removing privileges that are not required by the Data API.

-- These relations are read through RLS but are written only by vetted
-- SECURITY DEFINER commands/triggers. Cloud default privileges had left
-- additional INSERT/UPDATE/DELETE/TRUNCATE/REFERENCES/TRIGGER/MAINTAIN grants.
revoke all on table
  public.clinic_admin_events,
  public.clinical_record_events,
  public.session_program_records,
  public.test_data_cleanup_log
from public, anon, authenticated;

grant select on table
  public.clinic_admin_events,
  public.clinical_record_events,
  public.session_program_records,
  public.test_data_cleanup_log
to authenticated;

-- Audit sequence values are generated by owner-executed trigger functions;
-- browser-facing roles never need to advance or inspect them directly.
revoke all on sequence
  public.audit_events_id_seq,
  public.clinical_audit_events_id_seq,
  public.student_access_audit_events_id_seq
from public, anon, authenticated;

-- Lifecycle events are immutable evidence produced by the program commands.
-- The previous INSERT policy allowed an assigned writer to fabricate events.
drop policy if exists program_lifecycle_events_insert_granted
  on public.program_lifecycle_events;
revoke insert, update, delete, truncate, references, trigger, maintain
  on table public.program_lifecycle_events
  from authenticated;
