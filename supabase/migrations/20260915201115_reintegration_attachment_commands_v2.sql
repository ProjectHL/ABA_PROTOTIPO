create function private.attachment_upload_v2_valid(p_upload jsonb)
returns boolean language sql immutable security invoker set search_path='' as $$
  select private.jsonb_has_exact_keys(p_upload,array['purpose','mimeType','fileName','byteLength','sha256'])
    and jsonb_typeof(p_upload->'purpose')='string'
    and p_upload->>'purpose' in ('professional-avatar','student-photo','student-document','chat-attachment','commercial-document')
    and jsonb_typeof(p_upload->'mimeType')='string'
    and p_upload->>'mimeType' in ('application/pdf','image/jpeg','image/png')
    and jsonb_typeof(p_upload->'fileName')='string'
    and char_length(btrim(p_upload->>'fileName')) between 1 and 240
    and p_upload->>'fileName' !~ '[/\\]'
    and p_upload->>'fileName' !~ '[[:cntrl:]]'
    and private.is_safe_nonnegative_integer_json(p_upload->'byteLength')
    and (p_upload->>'byteLength')::bigint between 1 and
      case when p_upload->>'purpose'='professional-avatar' then 5242880 else 20971520 end
    and jsonb_typeof(p_upload->'sha256')='string'
    and p_upload->>'sha256' ~ '^[a-f0-9]{64}$'
    and case p_upload->>'purpose'
      when 'professional-avatar' then p_upload->>'mimeType' in ('image/jpeg','image/png')
      when 'student-photo' then p_upload->>'mimeType' in ('image/jpeg','image/png')
      else true end;
$$;

create function private.attachment_command_v2_valid(p_command jsonb)
returns boolean language plpgsql immutable security invoker set search_path='' as $$
declare v_action text; v_resource jsonb; v_upload jsonb; v_expected bigint;
begin
  if jsonb_typeof(p_command)<>'object' or jsonb_typeof(p_command->'action')<>'string'
    or jsonb_typeof(p_command->'operationId')<>'string' or not private.is_uuid_text(p_command->>'operationId')
    or jsonb_typeof(p_command->'idempotencyKey')<>'string' or not private.is_uuid_text(p_command->>'idempotencyKey')
    or jsonb_typeof(p_command->'attachmentId')<>'string' or not private.is_uuid_text(p_command->>'attachmentId')
    or not private.attachment_resource_v2_valid(p_command->'resource')
    or not private.is_safe_nonnegative_integer_json(p_command->'expectedVersion')
  then return false; end if;
  v_action:=p_command->>'action';v_resource:=p_command->'resource';
  v_expected:=(p_command->>'expectedVersion')::bigint;
  if v_action='reserve-upload' then
    if not private.jsonb_has_exact_keys(p_command,array[
      'operationId','idempotencyKey','attachmentId','resource','action','versionId',
      'expectedVersion','supersedesVersionId','upload'])
      or jsonb_typeof(p_command->'versionId')<>'string' or not private.is_uuid_text(p_command->>'versionId')
      or jsonb_typeof(p_command->'supersedesVersionId') not in ('string','null')
      or (jsonb_typeof(p_command->'supersedesVersionId')='string'
        and not private.is_uuid_text(p_command->>'supersedesVersionId'))
      or not private.attachment_upload_v2_valid(p_command->'upload') then return false; end if;
    v_upload:=p_command->'upload';
    if (v_expected=0)<>(p_command->>'supersedesVersionId' is null)
      or (v_expected>0 and p_command->>'versionId'=p_command->>'supersedesVersionId')
      or (v_upload->>'purpose'='professional-avatar')<>(v_resource->>'kind'='professional')
      or (v_upload->>'purpose'='student-photo')<>(v_resource->>'kind'='student')
      or (v_upload->>'purpose'='student-document' and v_resource->>'kind'<>'student')
      or (v_upload->>'purpose'='chat-attachment')<>(v_resource->>'kind'='chat')
      or (v_upload->>'purpose'='commercial-document')<>(v_resource->>'kind'='commercial')
    then return false; end if;
  elsif v_action='archive' then
    if not private.jsonb_has_exact_keys(p_command,array[
      'operationId','idempotencyKey','attachmentId','resource','action','expectedVersion','reason'])
      or v_expected=0 or jsonb_typeof(p_command->'reason')<>'string'
      or char_length(btrim(p_command->>'reason')) not between 1 and 2000 then return false; end if;
  elsif v_action='confirm-upload' then
    if not private.jsonb_has_exact_keys(p_command,array[
      'operationId','idempotencyKey','attachmentId','resource','action','versionId','expectedVersion'])
      or v_expected=0 or jsonb_typeof(p_command->'versionId')<>'string'
      or not private.is_uuid_text(p_command->>'versionId') then return false; end if;
  else return false; end if;
  return true;
exception when numeric_value_out_of_range then return false;
end;
$$;

create function private.attachment_version_dto_v2(p_version_id uuid)
returns jsonb language sql stable security definer set search_path='' as $$
  select jsonb_build_object(
    'id',v.id,'attachmentId',r.id,'resource',private.attachment_record_resource_v2(r),
    'version',v.version,'supersedesVersionId',v.supersedes_version_id,
    'upload',jsonb_build_object('purpose',r.purpose,'mimeType',v.mime_type,
      'fileName',v.original_name,'byteLength',v.byte_length,'sha256',v.sha256),
    'state',v.state,'bucket',v.bucket_id,'objectKey',v.object_key,
    'createdBy',v.created_by,'createdAt',v.created_at,'testBatchId',r.test_run_id)
  from public.attachment_versions v join public.attachment_records r on r.id=v.attachment_id
  where v.id=p_version_id;
$$;

create function private.attachment_envelope_v2(p_result jsonb,p_version_id uuid default null)
returns jsonb language sql stable security definer set search_path='' as $$
  select jsonb_build_object('result',p_result,'version',
    case when p_result->>'status'='acknowledged'
      then private.attachment_version_dto_v2(p_version_id) else null end);
$$;

create function public.aba_attachment_reserve_v2(p_organization_id uuid,p_command jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  v_actor uuid:=auth.uid();v_operation uuid;v_key uuid;v_attachment uuid;v_version_id uuid;
  v_expected bigint;v_previous uuid;v_resource jsonb;v_upload jsonb;v_replay jsonb;
  v_record public.attachment_records%rowtype;v_current public.attachment_versions%rowtype;
  v_kind text;v_test_run uuid;v_next integer;v_extension text;v_object_key text;
begin
  if p_organization_id is null or jsonb_typeof(p_command)<>'object'
    or jsonb_typeof(p_command->'operationId')<>'string' or not private.is_uuid_text(p_command->>'operationId')
    or jsonb_typeof(p_command->'idempotencyKey')<>'string' or not private.is_uuid_text(p_command->>'idempotencyKey')
    or jsonb_typeof(p_command->'attachmentId')<>'string' or not private.is_uuid_text(p_command->>'attachmentId')
  then raise exception using errcode='22023',message='attachment_command_identity_invalid';end if;
  v_operation:=(p_command->>'operationId')::uuid;v_key:=(p_command->>'idempotencyKey')::uuid;
  v_attachment:=(p_command->>'attachmentId')::uuid;
  if v_actor is null then return private.attachment_envelope_v2(
    private.command_rejected_result(v_operation,v_key,v_attachment,'permission-denied','Se requiere una sesión autenticada.'));
  end if;
  if not private.attachment_command_v2_valid(p_command) or p_command->>'action'<>'reserve-upload' then
    return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
      'validation-failed','La reserva de adjunto no cumple el contrato V2.'));
  end if;
  v_resource:=p_command->'resource';v_upload:=p_command->'upload';
  if not private.attachment_resource_authorized_v2(p_organization_id,v_resource,'student.edit') then
    return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
      'permission-denied','No tienes permiso vigente para adjuntar en este recurso.'));
  end if;
  v_replay:=private.command_identity_or_replay_result(
    p_organization_id,v_operation,v_key,v_attachment,'attachment-reserve-v2',p_command);
  v_version_id:=(p_command->>'versionId')::uuid;
  if v_replay is not null then return private.attachment_envelope_v2(v_replay,v_version_id);end if;

  v_expected:=(p_command->>'expectedVersion')::bigint;
  v_previous:=(p_command->>'supersedesVersionId')::uuid;v_kind:=v_resource->>'kind';
  if v_kind='student' then
    select c.test_run_id into v_test_run from public.clients c
    where c.organization_id=p_organization_id and c.id=(v_resource->>'studentId')::uuid for update;
    if not found then return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
      'resource-unavailable','La ficha ya no está disponible.'));end if;
    perform private.require_open_test_batch(p_organization_id,v_test_run);
  else
    perform 1 from public.organizations o where o.id=p_organization_id and o.status='active' for update;
    if not found then return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
      'resource-unavailable','La clínica ya no está activa.'));end if;
  end if;
  if not private.attachment_resource_authorized_v2(p_organization_id,v_resource,'student.edit') then
    return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
      'permission-denied','La autorización para adjuntar dejó de estar vigente.'));
  end if;
  if exists(select 1 from public.attachment_versions v where v.id=v_version_id) then
    return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
      'validation-failed','El identificador de versión ya está en uso.'));
  end if;

  if v_expected=0 then
    if exists(select 1 from public.attachment_records r where r.id=v_attachment) then
      return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
        'resource-unavailable','El adjunto ya existe; usa su versión vigente.'));
    end if;
    insert into public.attachment_records(
      id,organization_id,resource_kind,professional_user_id,client_id,conversation_id,
      commercial_document_id,purpose,state,version,created_by,test_run_id)
    values(v_attachment,case when v_kind='professional' then null else p_organization_id end,v_kind,
      case when v_kind='professional' then (v_resource->>'userId')::uuid end,
      case when v_kind in ('student','chat') then (v_resource->>'studentId')::uuid end,
      case when v_kind='chat' then (v_resource->>'conversationId')::uuid end,
      case when v_kind='commercial' then (v_resource->>'documentId')::uuid end,
      v_upload->>'purpose','pending-upload',0,v_actor,v_test_run)
    returning * into v_record;v_next:=1;
  else
    select r.* into v_record from public.attachment_records r where r.id=v_attachment for update;
    if not found or private.attachment_record_resource_v2(v_record)<>v_resource or v_record.purpose<>v_upload->>'purpose' then
      return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
        'resource-unavailable','El adjunto no coincide con el recurso solicitado.'));
    end if;
    if v_record.version::bigint<>v_expected then
      return private.attachment_envelope_v2(private.command_version_conflict_result(
        v_operation,v_key,v_attachment,v_expected,v_record.version,'La versión del adjunto cambió.'));
    end if;
    if v_record.state not in ('available','failed') or v_record.current_version_id<>v_previous then
      return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
        'invalid-transition','La sustitución no continúa la versión vigente.'));
    end if;
    select v.* into v_current from public.attachment_versions v where v.id=v_record.current_version_id;
    v_next:=v_record.version+1;
  end if;

  v_extension:=case v_upload->>'mimeType' when 'application/pdf' then '.pdf'
    when 'image/jpeg' then '.jpg' else '.png' end;
  v_object_key:='clinic/'||p_organization_id::text||'/'||v_kind||'/'||
    case v_kind when 'professional' then v_resource->>'userId' when 'commercial' then v_resource->>'documentId'
      when 'chat' then v_resource->>'conversationId' else v_resource->>'studentId' end||'/'||
    v_attachment::text||'/'||v_version_id::text||v_extension;
  insert into public.attachment_versions(
    id,attachment_id,version,supersedes_version_id,state,bucket_id,object_key,
    original_name,mime_type,byte_length,sha256,created_by)
  values(v_version_id,v_attachment,v_next,v_previous,'pending-upload','clinical-attachments',v_object_key,
    btrim(v_upload->>'fileName'),v_upload->>'mimeType',(v_upload->>'byteLength')::bigint,
    v_upload->>'sha256',v_actor);
  update public.attachment_records set current_version_id=v_version_id,version=v_next,
    state='pending-upload',archived_at=null where id=v_attachment;
  insert into public.attachment_events_v2(
    organization_id,attachment_id,version_id,action,actor_user_id,test_run_id)
  values(p_organization_id,v_attachment,v_version_id,'reserved',v_actor,v_test_run);
  if v_kind='student' then
    insert into public.audit_events(organization_id,actor_user_id,entity_type,entity_id,action,test_run_id)
    values(p_organization_id,v_actor,'client',(v_resource->>'studentId')::uuid,'updated',v_test_run);
  end if;
  return private.attachment_envelope_v2(private.issue_command_receipt(
    p_organization_id,v_operation,v_key,v_attachment,'attachment-reserve-v2',p_command,v_next,v_test_run),v_version_id);
end;
$$;

create function public.aba_attachment_archive_v2(p_organization_id uuid,p_command jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_actor uuid:=auth.uid();v_operation uuid;v_key uuid;v_attachment uuid;v_expected bigint;
  v_resource jsonb;v_replay jsonb;v_record public.attachment_records%rowtype;v_test_run uuid;
begin
  if p_organization_id is null or jsonb_typeof(p_command)<>'object'
    or jsonb_typeof(p_command->'operationId')<>'string' or not private.is_uuid_text(p_command->>'operationId')
    or jsonb_typeof(p_command->'idempotencyKey')<>'string' or not private.is_uuid_text(p_command->>'idempotencyKey')
    or jsonb_typeof(p_command->'attachmentId')<>'string' or not private.is_uuid_text(p_command->>'attachmentId')
  then raise exception using errcode='22023',message='attachment_command_identity_invalid';end if;
  v_operation:=(p_command->>'operationId')::uuid;v_key:=(p_command->>'idempotencyKey')::uuid;
  v_attachment:=(p_command->>'attachmentId')::uuid;
  if v_actor is null then return private.attachment_envelope_v2(private.command_rejected_result(
    v_operation,v_key,v_attachment,'permission-denied','Se requiere una sesión autenticada.'));end if;
  if not private.attachment_command_v2_valid(p_command) or p_command->>'action'<>'archive' then
    return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
      'validation-failed','El archivo lógico no cumple el contrato V2.'));end if;
  v_resource:=p_command->'resource';
  if not private.attachment_resource_authorized_v2(p_organization_id,v_resource,'student.edit') then
    return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
      'permission-denied','No tienes permiso vigente para archivar este adjunto.'));end if;
  v_replay:=private.command_identity_or_replay_result(
    p_organization_id,v_operation,v_key,v_attachment,'attachment-archive-v2',p_command);
  if v_replay is not null then
    select r.current_version_id into v_record.current_version_id from public.attachment_records r where r.id=v_attachment;
    return private.attachment_envelope_v2(v_replay,v_record.current_version_id);
  end if;
  select r.* into v_record from public.attachment_records r where r.id=v_attachment for update;
  if not found or private.attachment_record_resource_v2(v_record)<>v_resource then
    return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
      'resource-unavailable','El adjunto no corresponde al recurso.'));end if;
  if not private.attachment_resource_authorized_v2(p_organization_id,v_resource,'student.edit') then
    return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
      'permission-denied','La autorización para archivar dejó de estar vigente.'));end if;
  v_expected:=(p_command->>'expectedVersion')::bigint;
  if v_record.version::bigint<>v_expected then return private.attachment_envelope_v2(
    private.command_version_conflict_result(v_operation,v_key,v_attachment,v_expected,v_record.version,'La versión del adjunto cambió.'));
  end if;
  if v_record.state='archived' then return private.attachment_envelope_v2(private.command_rejected_result(
    v_operation,v_key,v_attachment,'invalid-transition','El adjunto ya está archivado.'));end if;
  if exists(select 1 from public.client_profiles_v2 p where p.photo_attachment_id=v_attachment)
    or exists(select 1 from public.consent_records c where c.evidence_attachment_id=v_attachment and c.status<>'superseded') then
    return private.attachment_envelope_v2(private.command_rejected_result(v_operation,v_key,v_attachment,
      'invalid-transition','Retira el adjunto de sus referencias activas antes de archivarlo.'));end if;
  update public.attachment_versions set state='archived',archived_at=now()
    where id=v_record.current_version_id;
  update public.attachment_records set state='archived',archived_at=now() where id=v_attachment;
  insert into public.attachment_events_v2(organization_id,attachment_id,version_id,action,actor_user_id,test_run_id)
  values(p_organization_id,v_attachment,v_record.current_version_id,'archived',v_actor,v_record.test_run_id);
  return private.attachment_envelope_v2(private.issue_command_receipt(
    p_organization_id,v_operation,v_key,v_attachment,'attachment-archive-v2',p_command,v_record.version,v_record.test_run_id),
    v_record.current_version_id);
end;
$$;

create function public.aba_attachment_list_v2(
  p_organization_id uuid,p_resource jsonb,p_include_archived boolean default false
)
returns jsonb language plpgsql stable security definer set search_path='' as $$
begin
  if not private.attachment_resource_authorized_v2(p_organization_id,p_resource,'student.view') then
    raise exception using errcode='42501',message='attachment_resource_view_required';end if;
  return coalesce((select jsonb_agg(private.attachment_version_dto_v2(v.id)
    order by v.created_at desc,v.version desc)
    from public.attachment_versions v join public.attachment_records r on r.id=v.attachment_id
    where private.attachment_record_resource_v2(r)=p_resource
      and (v.state='available' or (coalesce(p_include_archived,false) and v.state='archived'))),'[]'::jsonb);
end;
$$;

create function public.aba_attachment_read_v2(
  p_organization_id uuid,p_resource jsonb,p_version_id uuid
)
returns jsonb language plpgsql stable security definer set search_path='' as $$
begin
  if not private.attachment_resource_authorized_v2(p_organization_id,p_resource,'student.view') then
    raise exception using errcode='42501',message='attachment_resource_view_required';end if;
  perform 1 from public.attachment_records r
    join public.attachment_versions v on v.attachment_id=r.id
    where v.id=p_version_id and v.state='available' and private.attachment_record_resource_v2(r)=p_resource;
  if not found then raise exception using errcode='P0002',message='attachment_version_unavailable';end if;
  return private.attachment_version_dto_v2(p_version_id);
end;
$$;

